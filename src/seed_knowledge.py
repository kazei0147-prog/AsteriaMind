def main():
    from AsteriaMind.cognitive_star_map import CognitiveStarMap
    star = CognitiveStarMap('asteriamind.db')

    added = 0
    skipped = 0
    by_rel = {}
    for subj, rel, obj in SEED_KNOWLEDGE:
        # 质量门 (残片/虚词不进)
        from AsteriaMind.cognitive_star_map import _is_valid_entity_pair
        if not _is_valid_entity_pair(subj, obj):
            skipped += 1
            continue
        star.store(subj, rel, obj, "confirmed",
                   f"seed_knowledge: 百科常识包")
        added += 1
        by_rel[rel] = by_rel.get(rel, 0) + 1

    print(f"喂入: {added} 条 | 跳过: {skipped} 条")
    print(f"按关系: {by_rel}")
    named = star.conn.execute(
        "SELECT COUNT(*) FROM directed_edges "
        "WHERE relation IN ('IS_A','CAN','NOT_CAN','HAS','EATS','LIVES_IN','NOT_IS_A')"
    ).fetchone()[0]
    print(f"知识层命名边总数: {named}")


if __name__ == "__main__":
    main()
