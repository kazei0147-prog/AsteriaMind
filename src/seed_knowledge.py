def seed_star_map(db_path: str = "asteriamind.db"):
    star = CognitiveStarMap(db_path)
    cur = star.conn.cursor()
    ts = time.time()

    all_triples = (IS_A_HIERARCHY + ABILITIES + FEATURES +
                   ORBITS + EATS + LIVES_IN)
    added = 0

    for subj, pred, obj in all_triples:
        star.store(subj, pred, obj, "confirmed",
                    f"种子: {subj} {pred} {obj}")
        # 两倍权重: 种子知识高置信
        _incr_directed(cur, subj, obj, pred, "confirmed", ts)
        _incr_directed(cur, subj, obj, pred, "confirmed", ts)
        added += 1

    for text in SEED_TEXTS:
        star.spread_write(text)

    star.conn.commit()
    n = star.count()
    de = cur.execute("SELECT COUNT(*) FROM directed_edges").fetchone()[0]
    co = cur.execute("SELECT COUNT(*) FROM co_occurrence").fetchone()[0]
    print(f"v2 种子灌入: {added} 三元组 + {len(SEED_TEXTS)} 段文本")
    print(f"星图: {n} 节点, {de} 有向边, {co} 共现")
    return star


if __name__ == "__main__":
    seed_star_map()
